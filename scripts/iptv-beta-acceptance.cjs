"use strict";
const { spawnSync } = require("node:child_process");
const { mkdtempSync, mkdirSync, writeFileSync } = require("node:fs");
const { tmpdir } = require("node:os");
const { join, resolve } = require("node:path");
const assert = require("node:assert/strict");
const root = resolve(__dirname, "..");
const testBuild = resolve(root, process.env.IPTV_TEST_BUILD || "dist");
const output = join(root, "artifacts", "iptv-beta");
if (!process.versions.electron) {
  mkdirSync(output, { recursive: true });
  const env = { ...process.env, SEEING_STONE_IPTV_ACCEPTANCE_PROFILE: mkdtempSync(join(tmpdir(), "ss-iptv-electron-")) };
  delete env.ELECTRON_RUN_AS_NODE;
  const result = spawnSync(require("electron"), [__filename], { cwd: root, env, windowsHide: true, timeout: 180000, stdio: "inherit" });
  if (result.error) throw result.error;
  process.exitCode = result.status ?? 1;
} else {
  run().catch(error => { console.error("IPTV Electron acceptance failed:", error.message); require("electron").app.exit(1); });
}

async function run() {
  const { app, BrowserWindow } = require("electron");
  if (process.env.IPTV_GUIDE_ONLY === "1") {
    BrowserWindow.prototype.show = function () {};
    BrowserWindow.prototype.focus = function () {};
  }
  const profile = process.env.SEEING_STONE_IPTV_ACCEPTANCE_PROFILE;
  if (!profile) throw new Error("Launch through the test wrapper.");
  app.setPath("userData", profile);
  app.disableHardwareAcceleration();
  app.commandLine.appendSwitch("disable-gpu");
  const { createLiveTvTestServer } = require("./live-tv-test-server.cjs");
  const providerState = {};
  const fixture = createLiveTvTestServer({ port: 0, bind: "127.0.0.1", catalogueSize: 123, providerState });
  await fixture.listen();
  const address = `http://127.0.0.1:${fixture.server.address().port}`;
  const windowPromise = new Promise(resolveWindow => app.once("browser-window-created", (_event, window) => resolveWindow(window)));
  let testPlayer;
  const { MpvPlayerService } = require(join(testBuild, "main/services/mpvPlayer.js"));
  const start = MpvPlayerService.prototype.start;
  MpvPlayerService.prototype.start = function (...args) { testPlayer = this; return start.apply(this, args); };
  require(join(testBuild, "main/index.js"));
  const window = await windowPromise;
  if (process.env.IPTV_GUIDE_ONLY === "1") window.webContents.setBackgroundThrottling(false);
  // Other application panels use the same data-role names; keep every test action in IPTV.
  const js = source => window.webContents.executeJavaScript(source.replaceAll("document.querySelector('[data-", "document.querySelector('.iptv-screen [data-")).catch(error => { throw new Error(`${source.slice(0, 160)}: ${error.message}`); });
  const waitFor = async (source) => {
    const until = Date.now() + 25000;
    while (Date.now() < until) {
      if (await js(source).catch(() => false)) return;
      await new Promise(resolveDelay => setTimeout(resolveDelay, 100));
    }
    const status = await js("({status:document.querySelector('.iptv-screen [data-role=status]')?.textContent, setup:document.querySelector('.iptv-screen [data-role=setup-message]')?.textContent})");
    writeFileSync(join(output, "failure.png"), (await window.webContents.capturePage()).toPNG());
    throw new Error(`Timed out: ${source.slice(0, 160)}; ${JSON.stringify(status)}`);
  };
  const submit = async (name, username) => js(`(() => { const form = document.querySelector('[data-role=setup]'); const values = ${JSON.stringify({ name, address, username, password: "fixture-password" })}; for (const [key,value] of Object.entries(values)) form.elements.namedItem(key).value=value; form.requestSubmit(); })()`);
  await waitFor("!!document.querySelector('#loginIptvButton') && !!window.iptv && !!document.querySelector('.iptv-screen')");
  await waitFor("!document.querySelector('#loginView').classList.contains('is-hidden')");
  await js("document.getElementById('loginIptvButton').click()");
  await waitFor("!document.querySelector('.iptv-screen').classList.contains('is-hidden')");
  await submit("Synthetic account", "viewer");
  await waitFor("document.querySelector('[data-role=status]').textContent.includes('succeeded')");
  assert.equal(await js("document.querySelector('input[name=password]').value"), "");
  await waitFor("document.querySelectorAll('.iptv-item').length === 50");
  await waitFor("document.querySelector('.iptv-now-playing')?.textContent.startsWith('Now:')");
  await js("document.querySelector('[data-role=category-search]').value='int'; document.querySelector('[data-role=category-search]').dispatchEvent(new Event('input'))");
  assert.equal(await js("document.querySelector('[data-role=group]').options.length"), 2);
  assert.equal(await js("document.querySelector('[data-role=group]').options[1].textContent.startsWith('International')"), true);
  await js("document.querySelector('[data-role=category-search]').value=''; document.querySelector('[data-role=category-search]').dispatchEvent(new Event('input'))");
  assert.equal(await js("document.querySelector('[data-role=group]').options.length"), 3);
  assert.equal(await js("document.querySelector('[data-role=coverage]').textContent.includes('123 channels')"), true);
  assert.equal(await js("document.querySelector('#loginView').classList.contains('is-hidden')"), true);
  const firstTitle = await js("document.querySelector('.iptv-item h3').textContent");
  await js("document.querySelector('.iptv-favourite').click()");
  await waitFor("document.querySelector('.iptv-favourite')?.getAttribute('aria-pressed') === 'true'");
  assert.equal(await js("!document.querySelector('.iptv-screen').classList.contains('is-hidden')"), true);
  await js("document.querySelector('[data-action=favourites]').click()");
  await waitFor("document.querySelectorAll('.iptv-item').length === 1");
  await js("document.querySelector('.iptv-favourite').click()");
  await waitFor("document.querySelectorAll('.iptv-item').length === 0");
  await js("document.querySelector('[data-action=favourites]').click()");
  await waitFor("document.querySelectorAll('.iptv-item').length === 50");
  await js("document.querySelector('[data-action=next]').click()");
  await waitFor("document.querySelector('[data-role=page-status]').textContent.includes('Page 2')");
  assert.notEqual(await js("document.querySelector('.iptv-item h3').textContent"), firstTitle);
  await js("document.querySelector('[data-role=search]').value='日本'; document.querySelector('[data-role=search]').dispatchEvent(new Event('input'))");
  await waitFor("document.querySelectorAll('.iptv-item').length === 1 && document.querySelector('.iptv-item h3').textContent.includes('日本語')");
  const providerId = await js("window.iptv.list().then(rows => rows[0].provider.providerId)");
  assert.doesNotMatch(JSON.stringify(await js("window.iptv.list()")), /fixture-password|127\.0\.0\.1/);
  providerState.failAction = "get_series";
  await js("document.querySelector('[data-action=refresh]').click()");
  await waitFor("document.querySelector('[data-role=status]').classList.contains('is-error')");
  assert.equal(await js(`window.iptv.catalogue({providerId:${JSON.stringify(providerId)},contentType:'live'}).then(page => page.items.length)`), 50);
  providerState.failAction = null;
  await js("document.querySelector('[data-action=refresh]').click()");
  await waitFor("document.querySelector('[data-role=status]').textContent.includes('succeeded')");
  await js("document.querySelector('[data-type=movie]').click()");
  await waitFor("document.querySelector('.iptv-item h3')?.textContent === 'Fixture Movie'");
  await waitFor("document.querySelector('.iptv-poster-art img')?.naturalWidth > 0");
  assert.equal(await js("document.querySelector('.iptv-poster-art img').src.startsWith('data:image/png;base64,')"), true);
  await js("document.querySelector('[data-type=series]').click()");
  await waitFor("document.querySelector('.iptv-item h3')?.textContent === 'Fixture Series'");
  await waitFor("document.querySelector('.iptv-poster-art img')?.naturalWidth > 0");
  await js("document.querySelector('[data-type=live]').click()");
  await waitFor("document.querySelectorAll('.iptv-item').length === 50");
  const overflow = await js("document.querySelector('.iptv-screen').scrollWidth > document.querySelector('.iptv-screen').clientWidth + 1");
  assert.equal(overflow, false);
  writeFileSync(join(output, "catalogue.png"), (await window.webContents.capturePage()).toPNG());
  await js("document.querySelector('[data-action=guide]').click()");
  await waitFor("document.querySelectorAll('.iptv-guide-programme').length > 0");
  await js("document.querySelector('[data-role=search]').value='college'; document.querySelector('[data-role=search]').dispatchEvent(new Event('input'))");
  await waitFor("document.querySelector('.iptv-guide-programme')?.textContent.includes('College Football')");
  await new Promise(resolveDelay => setTimeout(resolveDelay, 500));
  writeFileSync(join(output, "programme-search.png"), (await window.webContents.capturePage()).toPNG());
  assert.equal(await js("document.querySelector('.iptv-guide-channel button').textContent.toLowerCase().includes('college')"), false);
  await js("document.querySelector('[data-role=search]').value=''; document.querySelector('[data-role=search]').dispatchEvent(new Event('input'))");
  await waitFor("document.querySelectorAll('.iptv-guide-row').length === 50 && !!document.querySelector('.iptv-guide-programme')");
  await js("document.querySelector('.iptv-guide-channel .iptv-favourite').click()");
  await waitFor("document.querySelector('.iptv-guide-channel .iptv-favourite')?.getAttribute('aria-pressed') === 'true'");
  assert.equal(await js("document.querySelector('.iptv-catalogue').clientHeight > innerHeight * .45"), true);
  assert.equal(await js("getComputedStyle(document.querySelector('.iptv-sidebar')).display"), "none");
  writeFileSync(join(output, "guide-expanded.png"), (await window.webContents.capturePage()).toPNG());
  await waitFor("(() => { const programme = document.querySelector('.iptv-guide-programme'); if (!programme) return false; programme.click(); return true; })()");
  await waitFor("!document.querySelector('[data-role=programme-details]').hidden");
  writeFileSync(join(output, "guide.png"), (await window.webContents.capturePage()).toPNG());
  if (process.env.IPTV_GUIDE_ONLY === "1") {
    console.log("IPTV guide search acceptance passed using an isolated, hidden profile without starting playback.");
    fixture.server.closeAllConnections(); await fixture.close(); window.close(); return;
  }
  await js("document.querySelector('[data-role=programme-details] button').click()");
  await waitFor("window.jellyfin.playback.getState().then(state => state.phase === 'playing' && !!state.iptvIdentity)");
  await waitFor("window.jellyfin.playback.getState().then(state => (state.diagnostics?.estimatedFps ?? state.diagnostics?.sourceFps ?? 0) > 0)");
  await waitFor("document.getElementById('playerMediaPills')?.textContent.includes('FPS')");
  const firstPlaybackId = await js("window.jellyfin.playback.getState().then(state => state.playbackId)");
  await js("document.getElementById('playerGoLiveButton').click()");
  await waitFor(`window.jellyfin.playback.getState().then(state => state.phase === 'playing' && !!state.iptvIdentity && state.playbackId !== ${JSON.stringify(firstPlaybackId)})`);
  writeFileSync(join(output, "playing.png"), (await window.webContents.capturePage()).toPNG());
  const beforeGuide = await js("window.jellyfin.playback.getState()");
  await js("document.getElementById('playerMiniGuideButton').click()");
  await waitFor("document.querySelectorAll('#playerMiniGuide .iptv-mini-channel').length > 1");
  await js("document.getElementById('playerMiniGuide').querySelector('[data-next]').click()");
  await waitFor("document.querySelector('#playerMiniGuide .iptv-mini-status').textContent.startsWith('Page 2')");
  await js("(() => { const input = document.querySelector('#playerMiniGuide input'); input.value = 'news'; input.dispatchEvent(new Event('input')); })()");
  await waitFor("document.querySelector('#playerMiniGuide .iptv-mini-status').textContent.startsWith('Page 1')");
  assert.equal((await js("window.jellyfin.playback.getState()")).playbackId, beforeGuide.playbackId);
  assert.equal((await js("window.jellyfin.playback.getState()")).phase, "playing");
  await js("(() => { const input = document.querySelector('#playerMiniGuide input'); input.value = ''; input.dispatchEvent(new Event('input')); })()");
  await waitFor("document.querySelectorAll('#playerMiniGuide .iptv-mini-channel').length === 20");
  await js("document.getElementById('playerMiniGuide').querySelector('[data-favourites]').click()");
  await waitFor("document.querySelectorAll('#playerMiniGuide .iptv-mini-channel').length === 1");
  await js("document.querySelector('#playerMiniGuide input').dispatchEvent(new KeyboardEvent('keydown', {key:'Escape', bubbles:true}))");
  assert.equal(await js("document.getElementById('playerMiniGuide').classList.contains('is-hidden')"), true);
  assert.equal((await js("window.jellyfin.playback.getState()")).playbackId, beforeGuide.playbackId);
  await js("document.getElementById('playerMiniGuideButton').click()");
  await waitFor("document.querySelectorAll('#playerMiniGuide .iptv-mini-channel').length === 20");
  writeFileSync(join(output, "iptv-mini-guide.png"), (await window.webContents.capturePage()).toPNG());
  await js("document.getElementById('playerMiniGuide').querySelector('.iptv-mini-channel[aria-current=false]').click()");
  await waitFor(`window.jellyfin.playback.getState().then(state => state.phase === 'playing' && state.iptvIdentity?.itemId !== ${JSON.stringify(beforeGuide.iptvIdentity.itemId)})`);
  const secondChannel = await js("window.jellyfin.playback.getState().then(state => state.iptvIdentity.itemId)");
  const secondPlaybackId = await js("window.jellyfin.playback.getState().then(state => state.playbackId)");
  await js("document.getElementById('playerGoLiveButton').click()");
  await waitFor(`window.jellyfin.playback.getState().then(state => state.phase === 'playing' && state.playbackId !== ${JSON.stringify(secondPlaybackId)})`);
  await waitFor("!document.getElementById('playerLastChannelButton').disabled");
  await js("document.getElementById('playerLastChannelButton').click()");
  await waitFor(`window.jellyfin.playback.getState().then(state => state.phase === 'playing' && state.iptvIdentity?.itemId === ${JSON.stringify(beforeGuide.iptvIdentity.itemId)})`);
  await js("document.getElementById('playerLastChannelButton').click()");
  await waitFor(`window.jellyfin.playback.getState().then(state => state.phase === 'playing' && state.iptvIdentity?.itemId === ${JSON.stringify(secondChannel)})`);
  await testPlayer.command(["screenshot-to-file", join(output, "decoded-frame.png"), "video"]);
  await js("document.getElementById('closePlayerButton').click()");
  await waitFor("window.jellyfin.playback.getState().then(state => !state.playbackId || state.phase === 'stopped')");
  await js("document.getElementById('loginIptvButton').click()");
  await waitFor("!document.querySelector('.iptv-screen').classList.contains('is-hidden')");
  const { DatabaseSync } = require("node:sqlite");
  const db = new DatabaseSync(join(profile, "localfirst.sqlite3"), { readOnly: true });
  assert.equal(db.prepare("SELECT COUNT(*) AS n FROM servers").get().n, 0);
  assert.equal(Buffer.from(db.prepare("SELECT protected_configuration FROM iptv_providers").get().protected_configuration).includes(Buffer.from("fixture-password")), false);
  db.close();
  await js("document.querySelector('[data-action=guide]').click()");
  assert.equal(await js("document.querySelector('.iptv-screen').classList.contains('is-guide-mode')"), false);
  await js("document.querySelector('[data-action=add]').click()");
  await submit("Expired account", "expired");
  await waitFor("document.querySelector('[data-role=provider-name]').textContent === 'Expired account' && document.querySelector('[data-role=status]').textContent.includes('rejected or expired')");
  writeFileSync(join(output, "expired-account.png"), (await window.webContents.capturePage()).toPNG());
  await require("./navigation-acceptance.cjs")({ window, js, waitFor, testBuild, output, providerId });
  writeFileSync(join(output, "result.json"), JSON.stringify({ passed: true, electron: process.versions.electron, accountSetup: true, osProtection: true, signedOutBrowsing: true, pagination: true, multilingualSearch: true, providerGuide: true, livePlayback: true, goLive: true, decodedFrameCapture: true, stopPlayback: true, failedRefreshRecovery: true, moviesAndSeries: true, expiredAccount: true, horizontalOverflow: overflow }, null, 2));
  console.log("IPTV Electron acceptance passed: protected setup, signed-out catalogues, search, pagination, provider guide, shared-player live playback and stop, refresh recovery and expired credentials.");
  fixture.server.closeAllConnections(); await fixture.close();
  window.close();
}
